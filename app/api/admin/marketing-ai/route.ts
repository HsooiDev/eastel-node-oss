import { NextRequest } from "next/server";
import { requireAdminCsrf, success, error } from "../_helpers";
import { generateReply, generateImage } from "@/lib/ai/gemini";
import fs from "fs/promises";
import { constants } from "node:fs";
import path from "path";
import db from "@/lib/db";
import { formatDate } from "@/lib/db-helpers";
import type { ResultSetHeader } from "mysql2/promise";
import { getMarketingPosterDirectory } from "@/lib/marketing-share-path";

async function ensureDir() {
  const directory = getMarketingPosterDirectory();
  await fs.mkdir(directory, { recursive: true });
  const root = await fs.lstat(directory);
  if (!root.isDirectory() || root.isSymbolicLink()) throw new Error("Poster storage is unavailable.");
  await fs.access(directory, constants.W_OK | constants.X_OK);
  return directory;
}

async function trackUsage(model: string) {
  const today = formatDate().split(" ")[0];
  await db.execute<ResultSetHeader>(
    `INSERT INTO \`ai_daily_usage\` (\`date\`, \`ai_provider\`, \`ai_model\`, \`count\`, \`daily_limit\`) 
     VALUES (?, 'gemini', ?, 1, NULL) 
     ON DUPLICATE KEY UPDATE \`count\` = \`count\` + 1`,
    [today, model]
  );
}

export async function POST(request: NextRequest) {
  try {
    const session = await requireAdminCsrf(request);
    if (!session) return error("Not authenticated.", 401);

    const body = await request.json();
    const { type, prompt, model } = body;

    if (!prompt) {
      return error("Prompt is required.");
    }

    if (type === "text") {
      const selectedModel = model || "gemini-2.5-flash";
      const defaultSysPrompt = "You are an expert marketing copywriter. Create short, catchy, and engaging slogans or catchphrases for a promotional poster based on the user's prompt. Provide 3-5 options separated by a new line. Keep them punchy and short.";
      const { text, model: actualModel } = await generateReply(
        selectedModel,
        prompt,
        [],
        body.systemPrompt || defaultSysPrompt
      );
      
      await trackUsage(actualModel);
      return success({ text });
    } 
    
    if (type === "image") {
      try {
        const STORAGE_DIR = await ensureDir();
        const selectedModel = model || 'imagen-3.0-generate-001';
        const imageBase64s = await generateImage(
          prompt, 
          selectedModel
        );
        
        if (!imageBase64s || imageBase64s.length === 0) {
          return error("No image generated by AI.");
        }

        await trackUsage(selectedModel);
        
        const buffer = Buffer.from(imageBase64s[0], 'base64');
        const filename = `ai_poster_${Date.now()}_${Math.random().toString(36).substring(7)}.jpeg`;
        const filePath = path.join(STORAGE_DIR, filename);
        
        await fs.writeFile(filePath, buffer);

        return success({
          message: "AI Image generated and saved successfully",
          filename,
          url: `/api/admin/posters/${filename}`
        });
      } catch (err: any) {
        console.error("Imagen generation error:", err);
        return error(err.message || "Failed to generate image.");
      }
    }

    return error("Invalid type. Must be 'text' or 'image'.");
  } catch (e) {
    console.error("Admin marketing AI POST error:", e);
    return error("Internal server error.", 500);
  }
}
